-- details page still reads it, so every write must keep populating it until it is dropped.
-- TODO PDJB-2019: drop ownership_type_before_pdjb955 once PDJB-2016 has removed the flag.

ALTER TABLE property_ownership RENAME COLUMN ownership_type TO ownership_type_before_pdjb955;

ALTER TABLE property_ownership ADD COLUMN ownership_type SMALLINT;

UPDATE property_ownership
SET ownership_type = CASE ownership_type_before_pdjb955
                       WHEN 0 THEN 2 -- FREEHOLD          -> SOLE_FREEHOLD
                       WHEN 1 THEN 1 -- LEASEHOLD         -> LEASEHOLD_ONLY
                       WHEN 2 THEN 3 -- SHARE_OF_FREEHOLD -> JOINT_TENANTS
                       WHEN 3 THEN 5 -- COMMONHOLD        -> COMMONHOLD
                     END;

ALTER TABLE property_ownership ALTER COLUMN ownership_type SET NOT NULL;

-- PDJB-1956: Tables for associated parties - freeholders, superior landlords and property
-- managers. Other than the freeholder backfill below, these are populated from PDJB-1957 onwards.

CREATE TABLE property_manager (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_date       TIMESTAMPTZ(6) DEFAULT current_timestamp NOT NULL,
    last_modified_date TIMESTAMPTZ(6),
    name               VARCHAR(255) NOT NULL,
    email              VARCHAR(255) NOT NULL
);

-- name, email and address_id are all nullable in both tables below: a landlord may tell us they
-- cannot provide a party's details, and a row with none of them set records "no details known".

CREATE TABLE freeholder (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_date          TIMESTAMPTZ(6) DEFAULT current_timestamp NOT NULL,
    last_modified_date    TIMESTAMPTZ(6),
    name                  VARCHAR(255),
    email                 VARCHAR(255),
    address_id            BIGINT,
    property_ownership_id BIGINT NOT NULL,
    CONSTRAINT fk_freeholder_address
        FOREIGN KEY (address_id) REFERENCES address(id),
    CONSTRAINT fk_freeholder_property_ownership
        FOREIGN KEY (property_ownership_id) REFERENCES property_ownership(id) ON DELETE CASCADE
);

CREATE INDEX idx_freeholder_property_ownership
    ON freeholder (property_ownership_id);

CREATE TABLE superior_landlord (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_date          TIMESTAMPTZ(6) DEFAULT current_timestamp NOT NULL,
    last_modified_date    TIMESTAMPTZ(6),
    name                  VARCHAR(255),
    email                 VARCHAR(255),
    address_id            BIGINT,
    property_ownership_id BIGINT NOT NULL,
    CONSTRAINT fk_superior_landlord_address
        FOREIGN KEY (address_id) REFERENCES address(id),
    CONSTRAINT fk_superior_landlord_property_ownership
        FOREIGN KEY (property_ownership_id) REFERENCES property_ownership(id) ON DELETE CASCADE
);

CREATE INDEX idx_superior_landlord_property_ownership
    ON superior_landlord (property_ownership_id);

-- Landlords are asked separately whether there are more people in the ownership chain, so an
-- absence of superior_landlord rows is ambiguous on its own: it could mean the landlord answered
-- no, or that we never asked. This records the answer, as marked_joint_landlord does for joint
-- landlords. It is nullable and left NULL for existing registrations, which were never asked.
-- Populated from PDJB-1957 onwards.
ALTER TABLE property_ownership ADD COLUMN has_superior_landlords BOOLEAN;

-- Every property whose ownership type implies a freeholder other than the landlord must have at
-- least one freeholder row, and a landlord cannot later edit a property to have none. Existing
-- registrations were never asked the question, so give each one a "no details known" placeholder
-- rather than leaving the invariant broken.
-- Of the types listed, only LEASEHOLD_ONLY and JOINT_TENANTS can result from the backfill above;
-- the rest are included so the rule reads as the complete rule rather than a subset of it.
INSERT INTO freeholder (property_ownership_id)
SELECT id
FROM property_ownership
WHERE ownership_type IN (
    0, -- NONE
    1, -- LEASEHOLD_ONLY
    3, -- JOINT_TENANTS
    4, -- TENANTS_IN_COMMON
    7, -- SHARE_OF_JOINT_TENANTS
    8  -- SHARE_OF_TENANTS_IN_COMMON
);

ALTER TABLE property_ownership ADD COLUMN property_manager_id BIGINT UNIQUE;

ALTER TABLE property_ownership ADD CONSTRAINT fk_property_ownership_property_manager
    FOREIGN KEY (property_manager_id) REFERENCES property_manager(id);
